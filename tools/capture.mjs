// Maker's screenshot rig: drives the real Vice Cover app in headless Edge
// (playwright-core from ../../tools-shots), serves app/ over loopback for the
// capture only, exercises the actual upload + export paths, and writes 3-4
// screenshots that satisfy the gate caps (<=256 KiB, long side <=1280, short
// side >=480, whole PNG/JPEG). Run: node tools/capture.mjs
import { createRequire } from 'node:module';
import { createServer } from 'node:http';
import { readFileSync, writeFileSync, mkdirSync, statSync, rmSync, readdirSync } from 'node:fs';
import { extname, join, normalize, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { chromium } = require('D:/Project X/makefun/tools-shots/node_modules/playwright-core');

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const appRoot = join(repoRoot, 'app');
const shotsDir = join(repoRoot, 'screenshots');
const tempDir = join(repoRoot, 'out', 'capture-temp');
mkdirSync(shotsDir, { recursive: true });
mkdirSync(tempDir, { recursive: true });
// screenshots/ is wholly generated by this rig; clear stale renders first.
for (const stale of readdirSync(shotsDir)) rmSync(join(shotsDir, stale));

const TYPES = {
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.png': 'image/png', '.ttf': 'font/ttf',
  '.txt': 'text/plain; charset=utf-8', '.json': 'application/json',
};
const server = createServer((req, res) => {
  let pathname = decodeURIComponent(new URL(req.url ?? '/', 'http://localhost').pathname);
  if (pathname.endsWith('/')) pathname += 'index.html';
  const target = resolve(join(appRoot, normalize(pathname)));
  if (!target.startsWith(appRoot + sep) && target !== appRoot) { res.writeHead(403).end(); return; }
  try {
    const body = readFileSync(target);
    res.writeHead(200, { 'content-type': TYPES[extname(target)] ?? 'application/octet-stream' });
    res.end(body);
  } catch { res.writeHead(404).end(); }
});
await new Promise((r) => server.listen(8123, '127.0.0.1', r));

const MAX_BYTES = 256 * 1024;
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const pageErrors = [];
page.on('pageerror', (e) => pageErrors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') pageErrors.push(m.text()); });

await page.goto('http://127.0.0.1:8123/', { waitUntil: 'load' });
await page.evaluate(() => window.viceCover.ready);
await page.waitForTimeout(400);

// Fit an exported cover into the caps: try PNG first (pure downscale of the
// app's own export); if it cannot fit 256 KiB with the short side >= 480,
// transcode the same scaled drawing to high-quality JPEG (the gate allows
// PNG or JPEG). No content edits either way.
async function fitShot(pngBuffer, baseName, aspect, nativeLong) {
  const maxLong = Math.min(1280, nativeLong);
  const minLong = aspect >= 1 ? Math.ceil(480 * aspect) : Math.ceil(480 / aspect);
  const drawScaled = (b64, w, h, type, quality) => page.evaluate(async ({ b64, w, h, type, quality }) => {
    const img = new Image();
    img.src = 'data:image/png;base64,' + b64;
    await img.decode();
    const c = document.createElement('canvas');
    c.width = w; c.height = h;
    c.getContext('2d').drawImage(img, 0, 0, w, h);
    return c.toDataURL(type, quality);
  }, { b64, w, h, type, quality });
  const dims = (long) => aspect >= 1
    ? { w: long, h: Math.round(long / aspect) }
    : { w: Math.round(long * aspect), h: long };

  let b64 = pngBuffer.toString('base64');
  for (let long = maxLong; long >= minLong; long -= 128) {
    const { w, h } = dims(long);
    const buf = Buffer.from((await drawScaled(b64, w, h, 'image/png')).split(',')[1], 'base64');
    if (buf.length <= MAX_BYTES) {
      writeFileSync(join(shotsDir, `${baseName}.png`), buf);
      return { name: `${baseName}.png`, w, h, bytes: buf.length };
    }
    b64 = buf.toString('base64');
  }
  const { w, h } = dims(maxLong);
  for (const quality of [0.92, 0.88, 0.84, 0.8]) {
    const buf = Buffer.from((await drawScaled(b64, w, h, 'image/jpeg', quality)).split(',')[1], 'base64');
    if (buf.length <= MAX_BYTES) {
      writeFileSync(join(shotsDir, `${baseName}.jpg`), buf);
      return { name: `${baseName}.jpg`, w, h, bytes: buf.length, quality };
    }
  }
  throw new Error(`${baseName}: cannot fit 256 KiB`);
}

// Export through the app's real Export PNG button and capture the download.
async function exportNative(sizeId, fileBase) {
  await page.evaluate((id) => window.viceCover.setSize(id), sizeId);
  const [download] = await Promise.all([
    page.waitForEvent('download', { timeout: 20000 }),
    page.evaluate(() => window.viceCover.exportPNG()),
  ]);
  const path = join(tempDir, fileBase);
  await download.saveAs(path);
  return readFileSync(path);
}

const results = [];

// 1) Cover shot: wide hero layout, Vice sunset grade — exported by the app
//    at 1920x1080, then scaled down to fit the caps.
await page.evaluate(() => {
  const v = window.viceCover;
  v.setLayout('hero');
  v.setGrade('sunset');
  v.setLettering('sunset');
  v.setCaption('VICE CITY', 'SUMMER NEVER ENDS');
  v.setPanelPhoto(0, 'scene:sunset-strip');
  v.setPanelPhoto(1, 'scene:neon-marina');
  v.setPanelPhoto(2, 'scene:ocean-drive');
  v.setPanelPhoto(3, 'scene:downtown-dusk');
});
await page.waitForTimeout(300);
const widePng = await exportNative('wide', 'export-wide-1920x1080.png');
results.push(await fitShot(widePng, '01-cover-vice-sunset', 1920 / 1080, 1920));

// 2) Editor shot: the app in the browser with a photo loaded through the
//    real file input (a scene rendered to PNG on disk stands in for a photo).
await page.evaluate(() => {
  const v = window.viceCover;
  v.setLayout('grid');
  v.setGrade('sunset');
  v.setLettering('sunset');
  v.setCaption('VICE CITY', 'SUMMER NEVER ENDS');
  v.setSize('square');
  v.setPanelPhoto(0, 'scene:sunset-strip');
  v.setPanelPhoto(1, 'scene:neon-marina');
  v.setPanelPhoto(2, 'scene:ocean-drive');
  v.setPanelPhoto(3, 'scene:golden-beach');
});
const scenePng = await page.evaluate(() => {
  const photo = window.viceCover.photos.get('scene:sunset-strip');
  return photo.source.toDataURL('image/png');
});
const uploadPath = join(tempDir, 'my-vice-photo.png');
writeFileSync(uploadPath, Buffer.from(scenePng.split(',')[1], 'base64'));
await page.setInputFiles('#photo-input', uploadPath);
await page.waitForTimeout(500);
const editorPath = join(shotsDir, '02-studio-editor.png');
await page.screenshot({ path: editorPath, type: 'png' });
if (statSync(editorPath).size > MAX_BYTES) {
  const jpgPath = editorPath.replace(/\.png$/, '.jpg');
  await page.screenshot({ path: jpgPath, type: 'jpeg', quality: 90 });
  rmSync(editorPath);
  results.push({ name: '02-studio-editor.jpg', w: 1280, h: 800, bytes: statSync(jpgPath).size });
} else {
  results.push({ name: '02-studio-editor.png', w: 1280, h: 800, bytes: statSync(editorPath).size });
}

